#!/bin/sh
# 一键验收（docker compose --profile demo run --rm demo）：
# 1) 并发竞态回归（进程内真实 ASGI + 真实 PostgreSQL 行锁，故障闸门注入交错）
# 2) 迁移缺片故障转移回归（模拟重启/内存池淘汰后的 failed 终态与安全重试）
# 3) 托管谱系逻辑销毁回归（销毁与迁移完成/分片领取提交并发的先后、幂等回执、墓碑）
# 4) 完整端到端验收（正常恢复 + 各类拒绝依据 + 并发重放 + 审计哈希链重放）
set -e

echo "######################################################################"
echo "# 1/4 并发回滚竞态回归 (scripts.race_recovery)"
echo "######################################################################"
python -m scripts.race_recovery

echo
echo "######################################################################"
echo "# 2/4 迁移缺片故障转移回归 (scripts.race_migration)"
echo "######################################################################"
python -m scripts.race_migration

echo
echo "######################################################################"
echo "# 3/4 托管谱系逻辑销毁回归 (scripts.race_destruction)"
echo "######################################################################"
python -m scripts.race_destruction

echo
echo "######################################################################"
echo "# 4/4 端到端验收 (scripts.demo)"
echo "######################################################################"
exec python -m scripts.demo
